#!/usr/bin/env python3
"""Generates the Pascal tables of the self-hosted compiler from the C++
X-macro files, so the two compilers cannot drift (SELFHOST.md RT4):

  include/pcc/Lexer/TokenKinds.def  ->  selfhost/tokens.inc
  include/pcc/AST/Builtins.def      ->  selfhost/builtins.inc
  CMakeLists.txt (project version)  ->  selfhost/version.inc

Usage:  utils/gen-selfhost-tables.py           (rewrite the .inc files)
        utils/gen-selfhost-tables.py --check   (exit 1 if they are stale)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def camel(ident):
    """integer_literal -> IntegerLiteral, kw_and -> KwAnd, l_paren -> LParen"""
    return "".join(p[:1].upper() + p[1:] for p in ident.split("_"))

def tokens_inc():
    text = open(os.path.join(ROOT, "include/pcc/Lexer/TokenKinds.def")).read()
    toks = []  # (id, spelling or None, flags or None)
    for m in re.finditer(r'^(TOK|PUNCT|KEYWORD)\((\w+)(?:,\s*"([^"]*)")?(?:,\s*(\w+))?\)',
                         text, re.M):
        toks.append((m.group(2), m.group(3), m.group(4)))
    out = ["{ Generated by utils/gen-selfhost-tables.py from",
           "  include/pcc/Lexer/TokenKinds.def. Do not edit. }",
           "type",
           "  TTokenKind = ("]
    names = ["tk" + camel(t[0]) for t in toks]
    for i, n in enumerate(names):
        out.append("    %s%s" % (n, "," if i + 1 < len(names) else ");"))
    out.append("  TKeywordInfo = record")
    out.append("    spelling: string[15];")
    out.append("    kind: TTokenKind;")
    out.append("    tpOnly: boolean; { reserved only with --mode=tp }")
    out.append("  end;")
    out.append("")
    out.append("const")
    out.append("  { the C++ token names, as --emit-tokens prints them }")
    out.append("  tokenNames: array[TTokenKind] of string[20] = (")
    for i, t in enumerate(toks):
        out.append("    '%s'%s" % (t[0], "," if i + 1 < len(toks) else ");"))
    out.append("  { spellings of punctuation and keywords ('' for the others) }")
    out.append("  tokenSpellings: array[TTokenKind] of string[15] = (")
    for i, t in enumerate(toks):
        out.append("    '%s'%s" % (t[1] or "", "," if i + 1 < len(toks) else ");"))
    kws = [t for t in toks if t[2]]
    out.append("  numKeywords = %d;" % len(kws))
    out.append("  keywords: array[1..numKeywords] of TKeywordInfo = (")
    for i, t in enumerate(kws):
        out.append("    (spelling: '%s'; kind: tk%s; tpOnly: %s)%s" % (
            t[1], camel(t[0]), "true" if t[2] == "KEYTP" else "false",
            "," if i + 1 < len(kws) else ");"))
    return "\n".join(out) + "\n"

def builtins_inc():
    text = open(os.path.join(ROOT, "include/pcc/AST/Builtins.def")).read()
    items = re.findall(r'^BUILTIN_(PROC|FUNC)\((\w+),\s*"([^"]*)"\)', text, re.M)
    out = ["{ Generated by utils/gen-selfhost-tables.py from",
           "  include/pcc/AST/Builtins.def. Do not edit. }",
           "type",
           "  TBuiltinKind = ("]
    for i, (_, ident, _) in enumerate(items):
        out.append("    bk%s%s" % (ident, "," if i + 1 < len(items) else ");"))
    out.append("")
    out.append("const")
    out.append("  builtinNames: array[TBuiltinKind] of string[15] = (")
    for i, (_, _, name) in enumerate(items):
        out.append("    '%s'%s" % (name, "," if i + 1 < len(items) else ");"))
    out.append("  builtinIsProcedure: array[TBuiltinKind] of boolean = (")
    for i, (kind, _, _) in enumerate(items):
        out.append("    %s%s" % ("true" if kind == "PROC" else "false",
                                  "," if i + 1 < len(items) else ");"))
    return "\n".join(out) + "\n"

def version_inc():
    text = open(os.path.join(ROOT, "CMakeLists.txt")).read()
    version = re.search(r'project\(pcc VERSION ([0-9.]+)', text).group(1)
    return ("{ Generated by utils/gen-selfhost-tables.py from CMakeLists.txt.\n"
            "  Do not edit. }\n"
            "const\n"
            "  pccVersion = '%s';\n" % version)

FILES = {"selfhost/tokens.inc": tokens_inc,
         "selfhost/builtins.inc": builtins_inc,
         "selfhost/version.inc": version_inc}

def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, gen in FILES.items():
        path = os.path.join(ROOT, rel)
        new = gen()
        old = open(path).read() if os.path.exists(path) else None
        if old != new:
            if check:
                stale.append(rel)
            else:
                open(path, "w").write(new)
                print("wrote", rel)
    if stale:
        print("stale (run utils/gen-selfhost-tables.py):", " ".join(stale))
        return 1
    if check:
        print("up to date")
    return 0

if __name__ == "__main__":
    sys.exit(main())
