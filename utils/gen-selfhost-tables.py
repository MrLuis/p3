#!/usr/bin/env python3
"""Generates the Pascal tables of the self-hosted compiler from the C++
X-macro files, so the two compilers cannot drift (SELFHOST.md RT4):

  include/p3/Lexer/TokenKinds.def  ->  selfhost/tokens.inc
  include/p3/AST/Builtins.def      ->  selfhost/builtins.inc
  include/p3/CodeGen/RuntimeFuncs.def -> selfhost/runtime.inc
  CMakeLists.txt (project version)  ->  selfhost/version.inc

Usage:  utils/gen-selfhost-tables.py           (rewrite the .inc files)
        utils/gen-selfhost-tables.py --check   (exit 1 if they are stale)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SPDX = "{ SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception }\n"

def camel(ident):
    """integer_literal -> IntegerLiteral, kw_and -> KwAnd, l_paren -> LParen"""
    return "".join(p[:1].upper() + p[1:] for p in ident.split("_"))

def tokens_inc():
    text = open(os.path.join(ROOT, "include/p3/Lexer/TokenKinds.def")).read()
    toks = []  # (id, spelling or None, flags or None)
    for m in re.finditer(r'^(TOK|PUNCT|KEYWORD)\((\w+)(?:,\s*"([^"]*)")?(?:,\s*(\w+))?\)',
                         text, re.M):
        toks.append((m.group(2), m.group(3), m.group(4)))
    out = ["{ Generated by utils/gen-selfhost-tables.py from",
           "  include/p3/Lexer/TokenKinds.def. Do not edit. }",
           "type",
           "  TTokenKind = ("]
    names = ["tk" + camel(t[0]) for t in toks]
    for i, n in enumerate(names):
        out.append("    %s%s" % (n, "," if i + 1 < len(names) else ");"))
    out.append("  TKeywordInfo = record")
    out.append("    spelling: string[15];")
    out.append("    kind: TTokenKind;")
    out.append("    level: byte; { reserved from this TLangMode on: 0 iso, 1 tp, 2 objfpc }")
    out.append("  end;")
    out.append("")
    out.append("const")
    out.append("  { the C++ token names, as --emit-tokens prints them }")
    out.append("  tokenNames: array[TTokenKind] of string[20] = (")
    for i, t in enumerate(toks):
        out.append("    '%s'%s" % (t[0], "," if i + 1 < len(toks) else ");"))
    out.append("  { spellings of punctuation and keywords ('' for the others) }")
    out.append("  tokenSpellings: array[TTokenKind] of string[15] = (")
    for i, t in enumerate(toks):
        out.append("    '%s'%s" % (t[1] or "", "," if i + 1 < len(toks) else ");"))
    kws = [t for t in toks if t[2]]
    out.append("  numKeywords = %d;" % len(kws))
    out.append("  keywords: array[1..numKeywords] of TKeywordInfo = (")
    for i, t in enumerate(kws):
        out.append("    (spelling: '%s'; kind: tk%s; level: %d)%s" % (
            t[1], camel(t[0]), {"KEYISO": 0, "KEYTP": 1, "KEYOBJ": 2}[t[2]],
            "," if i + 1 < len(kws) else ");"))
    return SPDX + "\n".join(out) + "\n"

def builtins_inc():
    text = open(os.path.join(ROOT, "include/p3/AST/Builtins.def")).read()
    items = re.findall(r'^BUILTIN_(PROC|FUNC)\((\w+),\s*"([^"]*)"\)', text, re.M)
    out = ["{ Generated by utils/gen-selfhost-tables.py from",
           "  include/p3/AST/Builtins.def. Do not edit. }",
           "type",
           "  TBuiltinKind = ("]
    for i, (_, ident, _) in enumerate(items):
        out.append("    bk%s%s" % (ident, "," if i + 1 < len(items) else ");"))
    out.append("")
    out.append("const")
    out.append("  builtinNames: array[TBuiltinKind] of string[20] = (")
    for i, (_, _, name) in enumerate(items):
        out.append("    '%s'%s" % (name, "," if i + 1 < len(items) else ");"))
    out.append("  builtinIsProcedure: array[TBuiltinKind] of boolean = (")
    for i, (kind, _, _) in enumerate(items):
        out.append("    %s%s" % ("true" if kind == "PROC" else "false",
                                  "," if i + 1 < len(items) else ");"))
    return SPDX + "\n".join(out) + "\n"

def runtime_inc():
    text = open(os.path.join(ROOT, "include/p3/CodeGen/RuntimeFuncs.def")).read()
    masks = {"PNONE": 0, "P0": 1, "P1": 2, "P2": 4, "P3": 8}

    def eval_mask(expr):
        val = 0
        for part in expr.split("|"):
            val |= masks[part.strip()]
        return val

    items = []
    pat = re.compile(
        r'^RUNTIME_FUNC\("([^"]+)",\s*([01]),\s*([01]),\s*([01]),\s*([01]),\s*([^,]+),\s*([^,]+),\s*([^)]+)\)',
        re.M,
    )
    for m in pat.finditer(text):
        items.append((
            m.group(1),
            m.group(2) == "1",
            m.group(3) == "1",
            m.group(4) == "1",
            m.group(5) == "1",
            eval_mask(m.group(6)),
            eval_mask(m.group(7)),
            eval_mask(m.group(8)),
        ))

    def b(v):
        return "true" if v else "false"

    out = [
        "{ Generated by utils/gen-selfhost-tables.py from",
        "  include/p3/CodeGen/RuntimeFuncs.def. Do not edit. }",
        "type",
        "  TRuntimeFuncAttr = record",
        "    name: string[31];",
        "    pureQuery, returnsFresh, returnsBool, neverFree: boolean;",
        "    readMask, writeMask, slotMask: byte;",
        "  end;",
        "",
        "const",
        "  numRuntimeFuncs = %d;" % len(items),
        "  runtimeFuncs: array[1..numRuntimeFuncs] of TRuntimeFuncAttr = (",
    ]
    for i, (name, pq, rf, rb, nf, rm, wm, sm) in enumerate(items):
        comma = "," if i + 1 < len(items) else ");"
        out.append(
            "    (name: '%s'; pureQuery: %s; returnsFresh: %s; returnsBool: %s; "
            "neverFree: %s; readMask: %d; writeMask: %d; slotMask: %d)%s"
            % (name, b(pq), b(rf), b(rb), b(nf), rm, wm, sm, comma)
        )
    return SPDX + "\n".join(out) + "\n"


def version_inc():
    text = open(os.path.join(ROOT, "CMakeLists.txt")).read()
    version = re.search(r'project\(p3 VERSION ([0-9.]+)', text).group(1)
    return (SPDX + "{ Generated by utils/gen-selfhost-tables.py from CMakeLists.txt.\n"
            "  Do not edit. }\n"
            "const\n"
            "  p3Version = '%s';\n" % version)

FILES = {"selfhost/tokens.inc": tokens_inc,
         "selfhost/builtins.inc": builtins_inc,
         "selfhost/runtime.inc": runtime_inc,
         "selfhost/version.inc": version_inc}

def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for rel, gen in FILES.items():
        path = os.path.join(ROOT, rel)
        new = gen()
        old = open(path).read() if os.path.exists(path) else None
        if old != new:
            if check:
                stale.append(rel)
            else:
                open(path, "w").write(new)
                print("wrote", rel)
    if stale:
        print("stale (run utils/gen-selfhost-tables.py):", " ".join(stale))
        return 1
    if check:
        print("up to date")
    return 0

if __name__ == "__main__":
    sys.exit(main())
