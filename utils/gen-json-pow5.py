#!/usr/bin/env python3
"""Writes rtl/json_pow5.inc: the 128-bit truncated powers of five 5^q,
q = -342..308, normalized so that the most significant bit is bit 127, as
the Eisel-Lemire number conversion of unit json uses them (the table of
fast_float, github.com/fastfloat/fast_float, script/table_generation.py).
table() follows that script: Copyright (c) 2021 The fast_float authors,
used under the Boost Software License 1.0 (THIRD_PARTY_NOTICES.md).

  python3 utils/gen-json-pow5.py [--check]
"""
import os, sys

def table():
    rows = []
    for q in range(-342, 0):
        power5 = 5 ** -q
        z = 0
        while (1 << z) < power5:
            z += 1
        if q >= -27:
            b = z + 127
            c = 2 ** b // power5 + 1
        else:
            b = 2 * z + 2 * 64
            c = 2 ** b // power5 + 1
            while c >= (1 << 128):
                c //= 2
        rows.append(c)
    for q in range(0, 308 + 1):
        power5 = 5 ** q
        while power5 < (1 << 127):
            power5 *= 2
        while power5 >= (1 << 128):
            power5 //= 2
        rows.append(power5)
    return rows

def text():
    out = ["{ SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception }",
           "{ Generated by utils/gen-json-pow5.py: do not edit. The 128-bit",
           "  truncated powers of five 5^q, q = -342..308 (high, low qwords),",
           "  for the Eisel-Lemire conversion of decimal numbers. }",
           "const",
           "  Pow5Smallest = -342;",
           "  Pow5Largest = 308;",
           "  Pow5Table: array[0..%d] of QWord = (" % (2 * 651 - 1)]
    rows = table()
    assert len(rows) == 651
    items = []
    for c in rows:
        items.append("QWord($%016X)" % (c >> 64))
        items.append("QWord($%016X)" % (c & ((1 << 64) - 1)))
    for i in range(0, len(items), 2):
        sep = "," if i + 2 < len(items) else ""
        out.append("    %s, %s%s" % (items[i], items[i + 1], sep))
    out.append("  );")
    return "\n".join(out) + "\n"

def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "json_pow5.inc")
    t = text()
    if "--check" in sys.argv:
        if open(path).read() != t:
            sys.exit("rtl/json_pow5.inc is not current: run utils/gen-json-pow5.py")
        return
    open(path, "w").write(t)

main()
