#!/usr/bin/env python3
"""Writes llvmtargets.inc for the self-hosted compiler's LLVM-C backend
(selfhost/pcllvm.pas, SELFHOST.md S11): declarations of the target
initialization functions of the LLVM it is linked with, and
llvmInitializeTargets, which calls them (llvm::InitializeAllTargets,
...TargetMCs and ...AsmPrinters, as the C++ pcc does).

LLVM-C's LLVMInitializeAllTargets is an inline function over the targets
of the LLVM build, so the list comes from that build's headers:

  utils/gen-llvm-targets.py <LLVM include dir> <output .inc>
"""
import os
import re
import sys


def names(include, header, macro):
    path = os.path.join(include, "llvm", "Config", header)
    return re.findall(r"^%s\((\w+)\)" % macro, open(path).read(), re.M)


def main():
    include, out = sys.argv[1], sys.argv[2]
    targets = names(include, "Targets.def", "LLVM_TARGET")
    printers = names(include, "AsmPrinters.def", "LLVM_ASM_PRINTER")
    funcs = []
    for t in targets:
        funcs += ["LLVMInitialize%sTargetInfo" % t, "LLVMInitialize%sTarget" % t,
                  "LLVMInitialize%sTargetMC" % t]
    funcs += ["LLVMInitialize%sAsmPrinter" % p for p in printers]
    lines = ["{ Generated by utils/gen-llvm-targets.py from the LLVM headers in",
             "  %s. Do not edit. }" % include, ""]
    for f in funcs:
        lines.append("procedure %s; cdecl; external name '%s';" % (f, f))
    lines += ["", "procedure llvmInitializeTargets;", "begin"]
    lines += ["  %s;" % f for f in funcs]
    lines += ["end;", ""]
    text = "\n".join(lines)
    if os.path.exists(out) and open(out).read() == text:
        return
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
